type WritingBand = "rich" | "mid" | "thin";

function writingBand(a: TaskAMetrics): WritingBand {
  if (a.charCount >= 250 && a.causalDensity >= 2) return "rich";
  if (a.charCount < 120 || a.causalDensity < 0.8) return "thin";
  return "mid";
}

